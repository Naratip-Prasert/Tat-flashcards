      const fresh = all.filter(f => !(used && used.has(f.gp)));
      const pool = (fresh.length ? fresh : all), tot = pool.reduce((a, f) => a + (f.lv === lv ? 3 : 1), 0);
      let r = Math.random() * tot, f = pool[0];
      for (const q of pool) { r -= q.lv === lv ? 3 : 1; if (r < 0) { f = q; break; } }
